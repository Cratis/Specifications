"""Generate deterministic, equivalent workloads without third-party Python dependencies."""
import argparse
import os
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = {"xunit-v2": "XUnit", "xunit-v3": "XUnit.v3", "nunit4": "NUnit", "tunit": "TUnit"}
if (ROOT.parent / "Source/NUnit5/NUnit5.csproj").exists():
    SOURCES["nunit5"] = "NUnit5"
HEADER = "// Copyright (c) Cratis. All rights reserved.\n// Licensed under the MIT license. See LICENSE file in the project root for full license information.\n// <auto-generated/>\n"


def positive(value):
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("must be positive")
    return number


def arguments():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=positive, default=os.getenv("N", "500"))
    parser.add_argument("--f", type=positive, default=os.getenv("F", "5"))
    parser.add_argument("--flavors", default=os.getenv("FLAVORS", ",".join(SOURCES)))
    return parser


def project(flavor, raw):
    packages = (["xunit"] if flavor == "xunit-v2" else ["xunit.v3.mtp-off"]) if flavor.startswith("xunit") else ["TUnit" if flavor == "tunit" else "nunit"]
    if flavor != "tunit":
        packages += ["Microsoft.NET.Test.Sdk", "xunit.runner.visualstudio" if flavor.startswith("xunit") else "NUnit3TestAdapter"]
    references = "" if raw else f'<ProjectReference Include="../../../Source/{SOURCES[flavor]}/{SOURCES[flavor]}.csproj" />'
    package_xml = {p: f'<PackageReference Include="{p}" />' for p in packages}
    if flavor.startswith("nunit"):
        # Preserve an optional NUnit 5 VersionOverride (and NUnit 4's override if
        # the central NUnit version later moves to 5), including in raw baselines.
        source = ROOT.parent / f"Source/{SOURCES[flavor]}/{SOURCES[flavor]}.csproj"
        reference = next(p for p in ET.parse(source).findall(".//PackageReference") if p.attrib["Include"].lower() == "nunit")
        package_xml["nunit"] = ET.tostring(reference, encoding="unicode").strip()
    return f'''<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFrameworks></TargetFrameworks>
    <TargetFramework>net10.0</TargetFramework>
    <AssemblyName>Benchmark</AssemblyName>
    <IsPackable>false</IsPackable>
    <IsTestProject>{str(flavor != 'tunit').lower()}</IsTestProject>
    <OutputType>{'Exe' if flavor in ('xunit-v3', 'tunit') else 'Library'}</OutputType>
    <LangVersion>latest</LangVersion>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
  </PropertyGroup>
  <ItemGroup>
    {references}
    {''.join(package_xml.values())}
  </ItemGroup>
</Project>
'''


def suite(flavor, raw, n, facts):
    xunit = flavor.startswith("xunit")
    using = "Xunit" if xunit else "TUnit.Core" if flavor == "tunit" else "NUnit.Framework"
    text = HEADER + f"using {using};\n"
    if not raw:
        text += "using Cratis.Specifications;\n"
        if flavor == "xunit-v3":
            text += "[assembly: Xunit.TestFramework(typeof(Cratis.Specifications.SpecificationTestFramework))]\n"
        elif flavor == "xunit-v2":
            text += '[assembly: Xunit.TestFramework("Cratis.Specifications.SpecificationTestFramework", "Cratis.Specifications.XUnit")]\n'
    text += "namespace BenchmarkSuite;\n"
    # A two-level given chain on one quarter of the concrete classes.
    base = "" if raw else " : Specification"
    text += f'''public abstract class given_seed{base}
{{
    protected int Seed;
    {'protected given_seed()' if raw else 'void Establish()'} => Seed = 7;
}}
public abstract class given_context : given_seed
{{
    protected string Label;
    {'protected given_context()' if raw else 'void Establish()'} => Label = "order-" + Seed;
}}
'''
    for index in range(n):
        chained = index % 4 == 0
        parent = " : given_context" if chained else base
        if raw and xunit:
            parent += (", " if parent else " : ") + "IAsyncLifetime"
        text += f"public class when_processing_{index:04d}{parent}\n{{\n"
        text += "    List<int> _items;\n    string _description;\n    int _total;\n"
        establish = 'new[] { Seed, 11, 13 }.ToList(); _description = Label + "-ready";' if chained else 'new[] { 7, 11, 13 }.ToList(); _description = "order-7-ready";'
        text += f"    void EstablishWork() {{ _items = {establish} }}\n"
        asynchronous = index % 3 == 0
        text += "    " + ("async Task" if asynchronous else "void") + " BecauseWork() { "
        if asynchronous:
            text += "await Task.Yield(); "
        text += '_total = _items.Sum(); _items.Add(_total); _description = _description.Trim(); }\n'
        if raw:
            # Match the shared class context of the opt-in Cratis runners. Raw xUnit
            # retains its native per-fact instance lifetime (documented in README).
            if xunit:
                return_type = "ValueTask" if flavor == "xunit-v3" else "Task"
                text += f"    public async {return_type} InitializeAsync() {{ EstablishWork(); " + ("await BecauseWork();" if asynchronous else "BecauseWork(); await Task.CompletedTask;") + " }\n"
                text += f"    public {return_type} DisposeAsync() => " + ("ValueTask.CompletedTask" if flavor == "xunit-v3" else "Task.CompletedTask") + ";\n"
            else:
                hook = "[Before(HookType.Test)]" if flavor == "tunit" else "[OneTimeSetUp]"
                text += f"    {hook} public " + ("async Task" if asynchronous else "void") + " Setup() { EstablishWork(); " + ("await " if asynchronous else "") + "BecauseWork(); }\n"
        else:
            text += "    void Establish() => EstablishWork();\n"
            text += "    " + ("Task" if asynchronous else "void") + " Because() => BecauseWork();\n"
        for fact in range(facts):
            actual, expected = [("_total", "31"), ("_items.Count", "4"), ("_description", '"order-7-ready"'), ("_items[3]", "31"), ("_items[0]", "7")][fact % 5]
            if not raw:
                assertion = f"{actual}.ShouldEqual({expected});"
            elif xunit:
                assertion = f"Assert.Equal({expected}, {actual});"
            elif flavor.startswith("nunit"):
                assertion = f"Assert.That({actual}, Is.EqualTo({expected}));"
            else:
                assertion = f"if ({actual} != {expected}) throw new Exception(\"Unexpected value\");"
            text += f"    [{'Fact' if xunit else 'Test'}] public void should_match_{fact}() {{ {assertion} }}\n"
        text += "}\n"
    return text


def generate(args):
    flavors = args.flavors.split(",")
    if len(set(flavors)) != len(flavors) or any(f not in SOURCES for f in flavors):
        raise ValueError(f"choose unique available flavors: {', '.join(SOURCES)}")
    projects = []
    for flavor in flavors:
        for raw in (False, True):
            directory = ROOT / "generated" / (flavor + ("-raw" if raw else ""))
            directory.mkdir(parents=True, exist_ok=True)
            (directory / "Benchmark.csproj").write_text(project(flavor, raw))
            (directory / "Suite.g.cs").write_text(suite(flavor, raw, args.n, args.f))
            projects.append({"flavor": flavor, "suite": "raw" if raw else "Cratis", "project": str(directory / "Benchmark.csproj")})
    return projects


if __name__ == "__main__":
    args = arguments().parse_args()
    projects = generate(args)
    print(f"Generated {len(projects)} projects, each with {args.n * args.f} tests")
