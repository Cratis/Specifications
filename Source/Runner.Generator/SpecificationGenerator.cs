using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Cratis.Specifications.Runner.Generator;

/// <summary>
/// Generates the registry of the specification classes of a test assembly, registered by a module initializer.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SpecificationGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var specifications = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                static (syntax, _) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node) is INamedTypeSymbol type
                    ? SpecificationModelBuilder.Build(type, syntax.SemanticModel.Compilation)
                    : null)
            .Where(static _ => _ is not null)
            .Collect();

        context.RegisterSourceOutput(specifications, static (output, models) => Generate(output, models));
    }

    static void Generate(SourceProductionContext output, IEnumerable<SpecificationModel> models)
    {
        var unique = models
            .GroupBy(_ => _.Uid, StringComparer.Ordinal)
            .Select(_ => _.First())
            .OrderBy(_ => _.Uid, StringComparer.Ordinal)
            .ToList();
        if (unique.Count == 0) return;

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable");
        builder.AppendLine("namespace Cratis.Specifications.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    static class SpecificationRegistration");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Register()");
        builder.AppendLine("        {");
        for (var index = 0; index < unique.Count; index++) builder.Append("            Specification").Append(index).AppendLine(".Register();");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        for (var index = 0; index < unique.Count; index++)
        {
            builder.AppendLine();
            SpecificationEmitter.Emit(builder, unique[index], $"Specification{index}");
        }

        builder.AppendLine("}");
        output.AddSource("CratisSpecifications.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
    }
}
